def pages(sdk: Path = SDK) -> dict[str, str]:
    out = {"c-api.md": c_page(sdk / "include" / "openrac" / "openrac_mod.h"),
           "cpp-api.md": cpp_page(sdk / "include" / "openrac" / "mod.hpp")}
    if (sdk / "api" / "members.tsv").is_file():
        out["by-area.md"] = area_page(sdk)
        out["changelog.md"] = changelog_page(sdk)
    for table in sorted((sdk / "bindings").glob("*.json")):
        out[f"hooks-{table.stem}.md"] = hooks_page(table)
    for types in sorted((sdk / "types").glob("*.d.luau")):
        game = types.name.split(".")[0]
        out["luau-api.md" if game == "rac1" else f"luau-api-{game}.md"] = luau_page(types, game)
    return out


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true", help="write nothing; fail when a page is stale")
    args = ap.parse_args(argv)
    out_dir = SDK / "docs" / "reference"
    stale = []
    for name, text in pages().items():
        path = out_dir / name
        if args.check:
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                stale.append(name)
        else:
            out_dir.mkdir(parents=True, exist_ok=True)
            if not path.is_file() or path.read_text(encoding="utf-8") != text:
                path.write_text(text, encoding="utf-8")
                print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print("gen_reference: stale (run python3 sdk/tools/gen_reference.py): " + ", ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
