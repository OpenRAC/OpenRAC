"""The mod interface's ABI, written down so that no change to it goes unseen.

    python3 sdk/tools/gen_api_lock.py [--check] [--against GIT_REF]

reads the SDK's C headers (include/openrac/*.h and include/openrac/games/*.h) with clang and writes:

    api/openrac_api.lock   the table: each member's place, offset and type
    api/types.lock         every other struct (size, each field's offset and type) and typedef
    api/macros.lock        every OPENRAC_ macro: its value, or its parameters for a helper macro

Offsets are for a 64-bit target (all of OpenRAC's platforms are 64-bit).

**Append only.** A built mod knows the table and the structs as they were when it was built. So a
row of a lock never changes or goes: a new member, field, typedef or macro may only be added (a
member or a field at the end of its struct). The tool refuses to write locks that change or drop
a row; --check also fails when the locks are not what the headers give (CI: .github/workflows/sdk.yml).
--against also holds the headers to the locks of a git ref (a pull request's base), so a lock
edited by hand cannot hide a break.
Only OPENRAC_MOD_API_MINOR and OPENRAC_MOD_TARGET_MINOR may change value.

Needs clang on PATH (or CLANG=<path>). Stdlib only.
"""
from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
import tempfile
from pathlib import Path

SDK = Path(__file__).resolve().parent.parent
TARGET = "x86_64-linux-gnu"
TABLE = "openrac_api"
# Macros whose value is meant to move.
MOVING = {"OPENRAC_MOD_API_MINOR", "OPENRAC_MOD_TARGET_MINOR"}
# Macros of the build, not of the interface.
SKIP_MACROS = {"OPENRAC_MOD_H", "OPENRAC_MOD_EXPORT"}
HEADER = "# Generated by sdk/tools/gen_api_lock.py from sdk/include. Do not edit. Rows are only ever added.\n"


def clang() -> str:
    return os.environ.get("CLANG", "clang")


def headers(sdk: Path) -> list[Path]:
    inc = sdk / "include" / "openrac"
    return sorted(inc.glob("*.h")) + sorted((inc / "games").glob("*.h"))


def source(sdk: Path) -> str:
    inc = sdk / "include"
    return "".join(f'#include "{h.relative_to(inc).as_posix()}"\n' for h in headers(sdk))


def run(args: list[str], text: str | None = None) -> str:
    done = subprocess.run(args, input=text, capture_output=True, text=True)
    if done.returncode != 0:
        raise SystemExit(f"{' '.join(args[:3])} ...: {done.stderr.strip()}")
    return done.stdout


def ast(sdk: Path) -> dict:
    out = run([clang(), "-x", "c", "-std=c99", "-fsyntax-only", f"--target={TARGET}", f"-I{sdk / 'include'}",
               "-Xclang", "-ast-dump=json", "-"], source(sdk))
    return json.loads(out)


def node_file(node: dict) -> str | None:
    """The file a node says it is in. clang's JSON names a file only where it changes."""
    for where in (node.get("loc", {}), node.get("range", {}).get("begin", {})):
        for loc in (where, where.get("spellingLoc", {}), where.get("expansionLoc", {})):
            if "file" in loc:
                return loc["file"]
    return None


def records(tree: dict, sdk: Path) -> tuple[dict[str, list[tuple[str, str]]], dict[str, str]]:
    """Named structs (by typedef name) with their fields as (path, type), and the other typedefs."""
    by_id: dict[str, dict] = {}

    def index(node: dict) -> None:
        if node.get("kind") == "RecordDecl" and node.get("completeDefinition"):
            by_id[node["id"]] = node
        for child in node.get("inner", []):
            index(child)

    index(tree)

    def fields(rec: dict, prefix: str) -> list[tuple[str, str]]:
        out: list[tuple[str, str]] = []
        inner = rec.get("inner", [])
        for i, child in enumerate(inner):
            if child.get("kind") != "FieldDecl":
                continue
            qual = child["type"]["qualType"]
            name = child.get("name", "")
            anon = "(anonymous" in qual or "(unnamed" in qual
            if anon:
                # The record defined just before the field is its type.
                sub = next((c for c in reversed(inner[:i]) if c.get("kind") == "RecordDecl"), None)
                kind = "union" if sub and sub.get("tagUsed") == "union" else "struct"
                if sub is not None:
                    path = f"{prefix}{name}." if name else prefix
                    if name:
                        out.append((f"{prefix}{name}", f"{kind} {{...}}"))
                    out.extend(fields(sub, path))
                    continue
            out.append((f"{prefix}{name}", qual))
        return out

    structs: dict[str, list[tuple[str, str]]] = {}
    typedefs: dict[str, str] = {}
    include = (sdk / "include").resolve()
    current: str | None = None
    for node in tree.get("inner", []):
        current = node_file(node) or current
        if node.get("isImplicit") or current is None or not Path(current).resolve().is_relative_to(include):
            continue
        if node.get("kind") == "TypedefDecl":
            name = node["name"]
            qual = node["type"]["qualType"]
            owned = node.get("inner", [{}])[0].get("ownedTagDecl") or \
                node.get("inner", [{}])[0].get("inner", [{}])[0].get("ownedTagDecl") \
                if node.get("inner") else None
            decl = None
            if owned and owned.get("id") in by_id:
                decl = by_id[owned["id"]]
            elif qual.startswith(("struct ", "union ")):
                tag = qual.split(" ", 1)[1]
                decl = next((r for r in by_id.values() if r.get("name") == tag), None)
            if decl is not None:
                structs[name] = fields(decl, "")
            else:
                typedefs[name] = " ".join(qual.split())
    return structs, typedefs


def layout(sdk: Path, structs: dict[str, list[tuple[str, str]]]) -> dict[str, tuple[int, dict[str, int]]]:
    """Each struct's size and its fields' offsets, from a program clang builds and runs."""
    lines = [source(sdk), "#include <stdio.h>", "#include <stddef.h>", "int main(void) {"]
    for name, fs in structs.items():
        lines.append(f'    printf("S {name} %zu\\n", sizeof({name}));')
        for path, qual in fs:
            if qual.endswith("{...}"):
                continue
            lines.append(f'    printf("F {name} {path} %zu\\n", offsetof({name}, {path}));')
    lines += ["    return 0;", "}"]
    with tempfile.TemporaryDirectory() as tmp:
        c = Path(tmp) / "layout.c"
        exe = Path(tmp) / "layout"
        c.write_text("\n".join(lines) + "\n")
        run([clang(), "-std=c99", "-w", f"-I{sdk / 'include'}", "-o", str(exe), str(c)])
        out = run([str(exe)])
    sizes: dict[str, tuple[int, dict[str, int]]] = {}
    for line in out.splitlines():
        part = line.split(" ")
        if part[0] == "S":
            sizes[part[1]] = (int(part[2]), {})
        else:
            sizes[part[1]][1][part[2]] = int(part[3])
    return sizes


def macros(sdk: Path) -> dict[str, str]:
    out = run([clang(), "-x", "c", "-std=c99", "-E", "-dM", f"--target={TARGET}", f"-I{sdk / 'include'}", "-"],
              source(sdk))
    found: dict[str, str] = {}
    for line in out.splitlines():
        m = re.match(r"#define (OPENRAC_\w+)(\([^)]*\))?(?:\s+(.*))?$", line)
        if not m or m.group(1) in SKIP_MACROS:
            continue
        name, params, value = m.group(1), m.group(2), (m.group(3) or "").strip()
        found[name] = f"helper{params}" if params is not None else " ".join(value.split())
    return found


def generate(sdk: Path = SDK) -> dict[str, list[str]]:
    """The three locks as their rows (a row's first column is its key)."""
    structs, typedefs = records(ast(sdk), sdk)
    if TABLE not in structs:
        raise SystemExit(f"no {TABLE} in sdk/include")
    sizes = layout(sdk, structs)

    def rows_of(name: str, place: bool) -> list[str]:
        rows = []
        for i, (path, qual) in enumerate(structs[name]):
            off = sizes[name][1].get(path, "-")
            rows.append(f"{i}\t{path}\t{off}\t{' '.join(qual.split())}" if place else
                        f"{name}\t{path}\t{off}\t{' '.join(qual.split())}")
        return rows

    api = rows_of(TABLE, True)
    types: list[str] = []
    for name in sorted(structs):
        if name == TABLE:
            continue
        types.append(f"{name}\t(size)\t{sizes[name][0]}\t-")
        types.extend(rows_of(name, False))
    for name in sorted(typedefs):
        types.append(f"{name}\t(typedef)\t-\t{typedefs[name]}")
    macro_rows = [f"{k}\t{v}" for k, v in sorted(macros(sdk).items())]
    return {"openrac_api.lock": api, "types.lock": types, "macros.lock": macro_rows}


def read_lock(path: Path) -> list[str]:
    if not path.exists():
        return []
    return [l for l in path.read_text().splitlines() if l and not l.startswith("#")]


def key(lock: str, row: str) -> str:
    c = row.split("\t")
    if lock == "openrac_api.lock":
        return c[1]
    if lock == "types.lock":
        return f"{c[0]}\t{c[1]}"
    return c[0]


def compare(lock: str, old: list[str], new: list[str]) -> list[str]:
    """What breaks the append-only rule, going from `old` to `new` rows."""
    problems: list[str] = []
    if lock == "openrac_api.lock":
        if new[: len(old)] != old:
            for i, row in enumerate(old):
                if i >= len(new) or new[i] != row:
                    got = new[i] if i < len(new) else "nothing"
                    problems.append(f"{lock}: member {i} was '{row}', is '{got}' (members are only added at the end)")
                    break
        return problems
    new_by = {key(lock, r): r for r in new}
    for row in old:
        k = key(lock, row)
        if k not in new_by:
            problems.append(f"{lock}: '{row}' is gone")
            continue
        if new_by[k] == row:
            continue
        c_old, c_new = row.split("\t"), new_by[k].split("\t")
        if lock == "macros.lock" and k in MOVING:
            continue
        if lock == "types.lock" and c_old[1] == "(size)":
            # A struct may grow when fields were only added at its end; the field rows say so.
            if int(c_new[2]) > int(c_old[2]):
                continue
        problems.append(f"{lock}: '{row}' became '{new_by[k]}'")
    if lock == "types.lock":
        # New fields of an old struct go after its old ones.
        old_structs = {r.split("\t")[0] for r in old}
        for name in old_structs:
            o = [r for r in old if r.split("\t")[0] == name and not r.split("\t")[1].startswith("(")]
            n = [r for r in new if r.split("\t")[0] == name and not r.split("\t")[1].startswith("(")]
            if n[: len(o)] != o and not any(name in p for p in problems):
                problems.append(f"{lock}: the fields of {name} changed order (fields are only added at the end)")
    return problems


def read_lock_at(ref: str, name: str) -> list[str]:
    """A lock as git `ref` has it (none: no rows)."""
    path = (SDK / "api" / name).relative_to(SDK.parent).as_posix()
    done = subprocess.run(["git", "-C", str(SDK.parent), "show", f"{ref}:{path}"], capture_output=True, text=True)
    if done.returncode != 0:
        return []
    return [l for l in done.stdout.splitlines() if l and not l.startswith("#")]


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--check", action="store_true", help="write nothing; fail when a lock differs")
    ap.add_argument("--against", metavar="GIT_REF", help="also hold the headers to this ref's locks")
    ap.add_argument("--sdk", type=Path, default=SDK, help=argparse.SUPPRESS)
    args = ap.parse_args(argv)
    out_dir = args.sdk / "api"
    locks = generate(args.sdk)
    problems: list[str] = []
    stale: list[str] = []
    for name, rows in locks.items():
        old = read_lock(out_dir / name)
        problems += compare(name, old, rows)
        if args.against:
            problems += [f"{p} (against {args.against})" for p in compare(name, read_lock_at(args.against, name), rows)]
        if old != rows:
            stale.append(name)
    for p in problems:
        print(f"error: {p}", file=sys.stderr)
    if problems:
        print("The mod interface is append-only in 1.x: built mods depend on every row above.", file=sys.stderr)
        return 1
    if args.check:
        for name in stale:
            print(f"error: sdk/api/{name} is not what the headers give: run sdk/tools/gen_api_lock.py",
                  file=sys.stderr)
        return 1 if stale else 0
    out_dir.mkdir(exist_ok=True)
    for name, rows in locks.items():
        (out_dir / name).write_text(HEADER + "".join(r + "\n" for r in rows))
    for name in stale:
        print(f"wrote sdk/api/{name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
