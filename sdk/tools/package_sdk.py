"""The SDK as one archive, for writing a mod without a copy of OpenRAC.

    python3 sdk/tools/package_sdk.py [-o DIR]

writes DIR/openrac-mod-sdk-<version>.zip (default DIR: dist/) and its .sha256: the headers, the
CMake package, the template, the example, the packaging tool, the README, MODS.md and the license,
in one top folder openrac-mod-sdk-<version>/. <version> is --version (MAJOR.MINOR.PATCH: CI passes
what sdk/tools/bump_api.py --release-version gives, or the tag's), else <interface>.0; its
MAJOR.MINOR must be the interface's (openrac_mod.h, OPENRAC_MOD_API_MAJOR and _MINOR), sdk/VERSION's
and the CMake package's. The archive's VERSION and the templates' sdk.lock say that version. The
archive is the same bytes wherever it is made (stored, sorted, fixed times), so a pinned SHA-256
holds for every build of one version. .github/workflows/sdk.yml publishes it on the release
sdk-v<version>. The behaviour catalogue, sdk/catalogue/ (generated by sdk/tools/catalogue.py), goes
in too.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import re
import sys
import zipfile
from pathlib import Path

SDK = Path(__file__).resolve().parent.parent
ROOT = SDK.parent
# What goes in, relative to sdk/ (folders whole; tests/ is the C++ layer's test, built by sdk.yml), and the files from elsewhere in OpenRAC.
# types/ holds the script mods' type definitions (<game>.d.luau, from gen_binding.py); docs/ the
# modders' guides and the generated reference (gen_reference.py), beside MODS.md.
PARTS = ["README.md", "VERSION", "include", "cmake", "template", "template-script", "examples", "catalogue",
         "types", "tests", "docs", "tools/package_mod.py"]
# Each game's hook ids and their aliases, which package_mod.py checks a manifest's "hooks" against.
PARTS += [f"bindings/{p.name}" for p in sorted((SDK / "bindings").glob("*.ids.lock"))]
# The templates whose sdk.lock pins the SDK they come in.
TEMPLATES = ("template", "template-script")
# The files every mod repository shares (MODS.md, sections 10 and 11). template/ holds each one's
# source; template-script/ carries a byte-identical copy, so either template works as it is in a
# git checkout. test_package_sdk.py holds the copies to their source.
SHARED = (".github/workflows/build.yml", "tools/fetch_sdk.py", ".gitattributes")
EXTRA = {"docs/MODS.md": ROOT / "docs" / "port" / "MODS.md", "LICENSE": SDK / "LICENSE"}
SKIP = {"__pycache__", ".DS_Store", "build", "dist"}
URL = "https://github.com/OpenRAC/OpenRAC/releases/download/sdk-v{v}/openrac-mod-sdk-{v}.zip"
DATE = (2026, 1, 1, 0, 0, 0)


def interface(sdk: Path = SDK) -> str:
    """MAJOR.MINOR: the header's, which sdk/VERSION and the CMake package must say too."""
    header = (sdk / "include" / "openrac" / "openrac_mod.h").read_text()
    api = ".".join(re.search(rf"^#define OPENRAC_MOD_API_{k} (\d+)$", header, re.M).group(1) for k in ("MAJOR", "MINOR"))
    text = (sdk / "VERSION").read_text().strip()
    if text != api:
        raise SystemExit(f"sdk/VERSION {text!r} is not the interface's {api} (openrac_mod.h): run sdk/tools/bump_api.py")
    cmake = (sdk / "cmake" / "OpenRACModConfigVersion.cmake").read_text()
    if f'set(PACKAGE_VERSION "{api}")' not in cmake:
        raise SystemExit(f"cmake/OpenRACModConfigVersion.cmake does not say {api}: run sdk/tools/bump_api.py")
    return api


def version(sdk: Path = SDK, release: str | None = None) -> str:
    """The archive's MAJOR.MINOR.PATCH: `release` (CI passes the one bump_api.py --release-version
    gives, or a tag's), else <interface>.0 for a local build."""
    api = interface(sdk)
    if release is None:
        return f"{api}.0"
    m = re.fullmatch(r"(\d+\.\d+)\.\d+", release)
    if not m:
        raise SystemExit(f"--version {release!r} is not MAJOR.MINOR.PATCH")
    if m.group(1) != api:
        raise SystemExit(f"--version {release} is not for the interface {api} (openrac_mod.h)")
    return release


def pinned(sdk: Path, template: str, v: str) -> bytes:
    """A template's sdk.lock as the archive has it: pinned to the archive's own release (its sha256
    empty: an archive cannot name its own hash; fetch_sdk.py fills it from the release)."""
    lock = json.loads((sdk / template / "sdk.lock").read_text())
    lock["version"] = v
    lock["url"] = URL.format(v=v)
    lock["sha256"] = ""
    return (json.dumps(lock, indent=2, ensure_ascii=False) + "\n").encode()


def files(sdk: Path = SDK) -> dict[str, Path]:
    out: dict[str, Path] = {}
    for part in PARTS:
        p = sdk / part
        if p.is_file():
            out[part] = p
            continue
        for f in sorted(p.rglob("*")) if p.is_dir() else []:
            if f.is_file() and not SKIP.intersection(f.relative_to(sdk).parts):
                out[f.relative_to(sdk).as_posix()] = f
    for name, path in EXTRA.items():
        if path.is_file():
            out[name] = path
    return dict(sorted(out.items()))


def contents(sdk: Path, v: str) -> dict[str, bytes]:
    """Each file of the archive, by its name in the archive. VERSION and the templates' sdk.lock say
    the archive's exact version."""
    out = {name: path.read_bytes() for name, path in files(sdk).items()}
    out["VERSION"] = (v + "\n").encode()
    for template in TEMPLATES:
        if f"{template}/sdk.lock" in out:
            out[f"{template}/sdk.lock"] = pinned(sdk, template, v)
    return dict(sorted(out.items()))


def write(out_dir: Path, sdk: Path = SDK, release: str | None = None) -> Path:
    v = version(sdk, release)
    top = f"openrac-mod-sdk-{v}"
    out_dir.mkdir(parents=True, exist_ok=True)
    archive = out_dir / f"{top}.zip"
    with zipfile.ZipFile(archive, "w", zipfile.ZIP_STORED) as z:
        for name, data in contents(sdk, v).items():
            info = zipfile.ZipInfo(f"{top}/{name}", DATE)
            info.external_attr = (0o755 if name.endswith(".py") else 0o644) << 16
            info.create_system = 3
            z.writestr(info, data)
    digest = hashlib.sha256(archive.read_bytes()).hexdigest()
    (out_dir / f"{top}.zip.sha256").write_text(f"{digest}  {archive.name}\n")
    return archive


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("-o", "--out", type=Path, default=Path("dist"))
    ap.add_argument("--version", help="the release's MAJOR.MINOR.PATCH (default: <interface>.0)")
    args = ap.parse_args(argv)
    archive = write(args.out, release=args.version)
    print(archive, (args.out / (archive.name + ".sha256")).read_text().split()[0])
    return 0


if __name__ == "__main__":
    sys.exit(main())
