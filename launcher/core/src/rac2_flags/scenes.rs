//! Each planet's cut scenes, one flag a scene: "seen" is the scene's bit in the cinematics chunk
//! (43, at 0x00139768), which the scene players set when it plays (`func_002EB7E8`,
//! `func_002F53C8`) and the level's scene triggers read to skip it.
//!
//! Which scenes are a planet's comes from the executable's table at 0x001AD030 (the first scene
//! id of each level, read by `func_002EF010`): level `L`'s scenes are ids `T[L]` to `T[L + 1] - 1`.
//! The game's names for the scenes were not read, so they are numbered within the planet. The
//! scenes the planet files already name (43, 50, 56, 96, 137, 144, 152, 154) are left out here,
//! and so are the ids under 33 and from 168, which belong to no one planet. Notes in
//! `RAC2_SAVE_FORMAT.md`, "Advanced: cut scenes seen".

use super::{scene, Confidence, Flag};

const fn scene_seen(id: &'static str, level: usize, name: &'static str, scene_id: usize) -> Flag {
    Flag {
        id,
        level: Some(level),
        name,
        description:
            "Off, the scene plays again where the level still has a trigger for it; on, its trigger skips it. \
                      It does not do what the scene's event does.",
        place: scene(scene_id),
        confidence: Confidence::FromCode,
    }
}

