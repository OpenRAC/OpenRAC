namespace {

using openrac::renderer::es_source;
using openrac::renderer::Shader;

bool contains(const std::string& text, const char* part) {
    return text.find(part) != std::string::npos;
}

void translation() {
    const std::string source =
        "#version 410 core\nnoperspective out vec4 v;\nvoid main() { gl_ClipDistance[0] = 1.0; }\n";

    const std::string with = es_source(source, true, true);
    CHECK(with.rfind("#version 320 es\n", 0) == 0);
    CHECK(contains(with, "#extension GL_NV_shader_noperspective_interpolation : require"));
    CHECK(contains(with, "#extension GL_EXT_clip_cull_distance : require"));
    CHECK(contains(with, "precision highp float;"));
    CHECK(contains(with, "precision highp usamplerBuffer;"));
    CHECK(contains(with, "noperspective out vec4 v;"));
    CHECK(contains(with, "gl_ClipDistance[0]"));
    CHECK(!contains(with, "410"));

    const std::string without = es_source(source, false, false);
    CHECK(!contains(without, "#extension"));
    CHECK(!contains(without, "noperspective"));
    CHECK(contains(without, "out vec4 v;"));
    CHECK(!contains(without, "gl_ClipDistance"));
    CHECK(contains(without, "float openrac_clip_distance[8];"));
    CHECK(contains(without, "openrac_clip_distance[0] = 1.0;"));

    // A source that is not GLSL 4.10 is left alone.
    const std::string other = "#version 300 es\nvoid main() {}\n";
    CHECK(es_source(other, false, false) == other);
}

void build(const char* name, const char* vertex, const char* fragment) {
    Shader shader;
    std::string error;
    const bool ok = shader.build(name, vertex, fragment, error);
    if (!ok) {
        std::fprintf(stderr, "%s\n", error.c_str());
    }
    CHECK(ok);
    shader.release();
}

// A 4x frame cleared to one colour reads back as that colour, through resolved() and read_rgba().
void multisampled() {
    using namespace openrac::gl;
    openrac::renderer::FrameBuffer frame;
    std::string error;
    const bool made = frame.create(16, 8, error, 4);
    if (!made) {
        std::fprintf(stderr, "%s\n", error.c_str());
    }
    CHECK(made);
    if (!made) {
        return;
    }
    std::printf(
        "multisampled frame: %d samples, %s\n",
        frame.samples(),
        frame.resolves_itself() ? "resolved by the GPU" : "resolved by a copy"
    );
    glBindFramebuffer(GL_FRAMEBUFFER, frame.id());
    glViewport(0, 0, 16, 8);
    glClearColor(1.0f, 0.0f, 0.0f, 1.0f);
    glClear(GL_COLOR_BUFFER_BIT | GL_DEPTH_BUFFER_BIT);
    const std::vector<std::uint8_t> pixels = frame.read_rgba();
    CHECK(pixels.size() == 16u * 8u * 4u);
    CHECK(
        pixels.size() >= 4 && pixels[0] == 255 && pixels[1] == 0 && pixels[2] == 0
        && pixels[3] == 255
    );
    CHECK(pixels.size() >= 4 && pixels[pixels.size() - 4] == 255 && pixels[pixels.size() - 3] == 0);
    CHECK(glGetError() == GL_NO_ERROR);
    frame.release();
}

}  // namespace

int main() {
    translation();
    const auto fixed = openrac::renderer::shader_constants(
        "#version 410 core\nuniform int mode;\nuniform int mode_extra;\n",
        {{"mode", -2}, {"absent", 1}}
    );
    CHECK(fixed == "#version 410 core\nconst int mode = -2;\nuniform int mode_extra;\n");

#ifdef OPENRAC_VULKAN
    // Inspect generated bytecode, not just source text: fixed branches must disappear.
    const auto report = [](const char* name,
                           const std::string& vertex,
                           const std::string& fragment,
                           const std::string& compute,
                           std::initializer_list<openrac::renderer::ShaderIntConstant> controls,
                           std::string_view definitions) {
        openrac::vkgl::CompiledProgram reference, variant;
        std::string error;
        CHECK(openrac::vkgl::compile_program(vertex, fragment, reference, error, compute));
        const auto specialise = [&](std::string source) {
            if (!source.empty()) {
                source.insert(source.find('\n') + 1, definitions);
            }
            return openrac::renderer::shader_constants(std::move(source), controls);
        };
        CHECK(
            openrac::vkgl::compile_program(
                specialise(vertex), specialise(fragment), variant, error, specialise(compute)
            )
        );
        const auto& a = compute.empty() ? reference.fragment : reference.compute;
        const auto& b = compute.empty() ? variant.fragment : variant.compute;
        const auto branches = [](const auto& code) {
            unsigned count = 0;
            for (std::size_t at = 5; at < code.size();) {
                const auto words = code[at] >> 16;
                if (!words || words > code.size() - at) {
                    break;
                }
                count += (code[at] & 0xffffu) == 250u;  // OpBranchConditional
                at += words;
            }
            return count;
        };
        std::printf(
            "%s SPIR-V words: %zu -> %zu; conditional branches: %u -> %u\n",
            name,
            a.size(),
            b.size(),
            branches(a),
            branches(b)
        );
        CHECK(branches(b) < branches(a));
        for (const auto& control : controls) {
            CHECK(
                std::none_of(
                    variant.uniforms.begin(), variant.uniforms.end(), [&](const auto& uniform) {
                        return uniform.name == control.name;
                    }
                )
            );
        }
        if (!error.empty()) {
            std::fprintf(stderr, "%s\n", error.c_str());
        }
        CHECK(!b.empty() && b.size() < a.size());
    };
    report(
        "effect",
        openrac::renderer::shaders::effect_vert,
        openrac::renderer::shaders::direct_frag,
        "",
        {{"textured", 1}, {"distance_field", 0}, {"fog_enable", 0}, {"alpha_test", 0}},
        "#define OPENRAC_EFFECT_FIXED 1\n"
    );
    std::string horizons(openrac::renderer::shaders::gtao_evaluate_comp);
    horizons.insert(horizons.find('\n') + 1, openrac::renderer::shaders::surface_normal_glsl);
    horizons.insert(horizons.find('\n') + 1, openrac::renderer::shaders::gtao_common_glsl);
    report(
        "GTAO full resolution",
        "",
        "",
        horizons,
        {{"evaluation_scale", 1}, {"surface_normals_enabled", 1}},
        "#define OPENRAC_GTAO_SCALE 1\n#define OPENRAC_SURFACE_NORMALS 1\n"
    );
    report(
        "GTAO half resolution",
        "",
        "",
        horizons,
        {{"evaluation_scale", 2}, {"surface_normals_enabled", 1}},
        "#define OPENRAC_GTAO_SCALE 2\n#define OPENRAC_SURFACE_NORMALS 1\n"
    );
    std::string world_fragment(openrac::scene::shaders::mesh_frag);
    constexpr std::string_view marker = "// OPENRAC_UPSCALED_TEXTURE_COLOURS_SOURCE";
    world_fragment.replace(
        world_fragment.find(marker),
        marker.size(),
        "vec4 sample_upscaled_texture_colours(vec2 uv) { return texture(tex_T0, uv); }\n"
    );
    report(
        "static world alpha",
        openrac::scene::shaders::mesh_vert,
        world_fragment,
        "",
        {{"skinning", 0},
         {"metal_pass", 0},
         {"glow_pass", 0},
         {"translucent_pass", 0},
         {"effect_pass", 0},
         {"probe_effect", 0}},
        "#define OPENRAC_COLOUR_SPECIALISED 1\n#define OPENRAC_STATIC_COLOUR 1\n"
    );
    report(
        "probe tile kernel",
        "",
        "",
        openrac::lighting::shaders::probe_selection_comp,
        {{"select_regions", 0}},
        "#define OPENRAC_PROBE_TILES 1\n"
    );

    // Frontend call placement, before the vendor driver's own loop optimisations.
    const std::string probe_fixture = "#version 430 core\n#define OPENRAC_PROBE_PIXEL ivec2(-1)\n"
                                      + std::string(openrac::lighting::shaders::probes_glsl)
                                      + R"(layout(local_size_x=1) in;
layout(std430,binding=0) buffer Output { vec4 sample_result[]; };
uniform vec3 receiver_position,receiver_normal;
void main(){vec3 light;float confidence;
bool valid=sample_probe_grid(receiver_position,receiver_normal,vec3(0,0,.02),
    vec3(0),vec3(4),vec2(1,0),vec3(2),0,false,light,confidence);
sample_result[0]=vec4(light,valid?confidence:0.);})";
    const auto calls = [](const std::vector<std::uint32_t>& code) {
        std::unordered_map<unsigned, std::string> names;
        for (std::size_t at = 5; at < code.size();) {
            const auto count = code[at] >> 16, op = code[at] & 65535u;
            if (!count || at + count > code.size()) {
                break;
            }
            if (op == 5 && count > 2) {
                names[code[at + 1]] = reinterpret_cast<const char*>(&code[at + 2]);
            }
            at += count;
        }
        std::array<unsigned, 3> result{};
        unsigned function = 0, merge = 0;
        for (std::size_t at = 5; at < code.size();) {
            const auto count = code[at] >> 16, op = code[at] & 65535u;
            if (!count || at + count > code.size()) {
                break;
            }
            if (op == 54) {
                function = code[at + 2];
                merge = 0;
            }
            if (names[function].starts_with("sample_probe_grid(")) {
                if (op == 246) {
                    merge = code[at + 1];
                }
                if (op == 248 && code[at + 1] == merge) {
                    merge = 0;
                }
                if (op == 57) {
                    const auto& target = names[code[at + 3]];
                    if (merge && target.starts_with("probe_map_uv(")) {
                        ++result[0];
                    }
                    if (target.starts_with("probe_oct(")) {
                        ++result[merge ? 1 : 2];
                    }
                }
            }
            at += count;
        }
        return result;
    };
    openrac::vkgl::CompiledProgram original_probe, prepared_probe;
    std::string probe_error, prepared_source(probe_fixture);
    prepared_source
        .insert(prepared_source.find('\n') + 1, "#define OPENRAC_PROBE_RECEIVER_SETUP 1\n");
    CHECK(openrac::vkgl::compile_program("", "", original_probe, probe_error, probe_fixture));
    CHECK(openrac::vkgl::compile_program("", "", prepared_probe, probe_error, prepared_source));
    const auto original_calls = calls(original_probe.compute),
               prepared_calls = calls(prepared_probe.compute);
    std::printf(
        "Probe loop atlas-map calls %u -> %u; prepared oct calls inside/outside loop %u/%u\n",
        original_calls[0],
        prepared_calls[0],
        prepared_calls[1],
        prepared_calls[2]
    );
    CHECK(original_calls[0] == 2 && prepared_calls[0] == 0);
    CHECK(prepared_calls[1] == 1 && prepared_calls[2] == 1);
    if (!probe_error.empty()) {
        std::fprintf(stderr, "%s\n", probe_error.c_str());
    }

#endif
    openrac::test::GlContext context;
    std::string why;
    if (!context.open(why)) {
        std::printf("SKIP: no OpenGL context: %s\n", why.c_str());
        return openrac::test::failures() == 0 ? openrac::test::kSkip : openrac::test::result();
    }
#ifdef OPENRAC_VULKAN
    if (openrac::gl::is_vulkan()) {
        openrac::vkgl::NativeDevice device;
        CHECK(openrac::vkgl::native_device(device));
        VkPhysicalDeviceVulkan12Features features{
            VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_VULKAN_1_2_FEATURES
        };
        VkPhysicalDeviceFeatures2 available{VK_STRUCTURE_TYPE_PHYSICAL_DEVICE_FEATURES_2};
        available.pNext = &features;
        vkGetPhysicalDeviceFeatures2(device.physical, &available);
        CHECK(
            device.float16
            == bool(
                features.shaderFloat16
                && openrac::renderer::render_opt::enabled(
                    openrac::renderer::render_opt::Opt::ShaderFloat16
                )
            )
        );
        const auto before = openrac::vkgl::submission_counters().shader_fp16_ops;
        build(
            "precision capability",
            "#version 410 core\nvoid main(){gl_Position=vec4(0,0,0,1);}",
            "#version 410 core\nuniform vec4 colour;layout(location=0) out vec4 result;"
            "void main(){mp_vec3 c=mp_vec3(colour.rgb)*mp_float(.75);"
            "result=vec4(vec3(clamp(c,mp_vec3(0),mp_vec3(1))),colour.a);}"
        );
        const auto after = openrac::vkgl::submission_counters().shader_fp16_ops;
        CHECK(device.float16 ? after > before : after == before);
        std::printf(
            "Enabled FP16 arithmetic: %d; typed SPIR-V operations: %llu\n",
            int(device.float16),
            static_cast<unsigned long long>(after - before)
        );
    }
#endif
    namespace renderer_src = openrac::renderer::shaders;
    namespace viewer_src = openrac::scene::shaders;
    build("direct", renderer_src::direct_vert, renderer_src::direct_frag);
    build("effect", renderer_src::effect_vert, renderer_src::direct_frag);
    const std::string mesh_fragment = openrac::lighting::probe_mesh_fragment(viewer_src::mesh_frag);
    build("mesh", viewer_src::mesh_vert, mesh_fragment.c_str());
    if (openrac::gl::enhanced_rendering_available()) {
        build("shadow depth", viewer_src::shadow_depth_vert, viewer_src::hero_shadow_frag);
        std::string shadow_vertex(viewer_src::shadow_depth_vert),
            shadow_fragment(viewer_src::hero_shadow_frag);
        shadow_vertex.insert(shadow_vertex.find('\n') + 1, "#define OPENRAC_SHADOW_SOLID 1\n");
        shadow_fragment.insert(shadow_fragment.find('\n') + 1, "#define OPENRAC_SHADOW_SOLID 1\n");
        Shader shadow_solid;
        CHECK(shadow_solid.build("opaque shadow depth", shadow_vertex, shadow_fragment, why));
        CHECK(shadow_solid.uniform("view_projection") >= 0);
        CHECK(shadow_solid.uniform("tex_T0") == -1);
        CHECK(shadow_solid.uniform("palette_texture") == -1);
        CHECK(shadow_solid.uniform("skinning") == -1);
        CHECK(shadow_solid.uniform("material_colour") == -1);
        shadow_solid.release();
    }
    // The static layers' opaque pass (scene/level_renderer.cpp, m_solid).
    std::string solid(mesh_fragment);
    solid.insert(solid.find('\n') + 1, "#define OPENRAC_SOLID 1\n");
    build("mesh (solid)", viewer_src::mesh_vert, solid.c_str());
    build("sky", viewer_src::sky_vert, viewer_src::sky_frag);
    multisampled();
    return openrac::test::result();
}
