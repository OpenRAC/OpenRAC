#!/usr/bin/env python3
"""
OpenRAC's top-level helper: your discs, where each game's build expects its
inputs, and progress across all the games. Standard library only.

  python3 tools/openrac.py discs [--full]   identify the disc images in baserom/ and check them
  python3 tools/openrac.py setup [GAME/VERSION ...]
                                            place each game's inputs from those discs (hard links,
                                            and boot executables read out of the images)
  python3 tools/openrac.py progress [--fetch]
                                            write progress/summary.json and progress/README.md, then
                                            refresh the tables; --fetch first copies reports that a
                                            sister project publishes outside its tree
  python3 tools/openrac.py tables           refresh the generated tables (games, discs, checksums,
                                            progress, sources) in README.md, baserom/README.md,
                                            games/README.md and docs/SOURCES.md from game.json

Discs are recognised by the boot file SYSTEM.CNF names, whatever the image
is called, and checked against games/<game>/game.json: size and SHA-1, or
every checksum with --full. Nothing is downloaded and nothing leaves your
machine; baserom/ and every placed input are ignored by git.
"""
import hashlib
import json
import os
import subprocess
import sys
import zlib
from pathlib import Path
from urllib.parse import urlencode

from openrac_common import digest, files, games, iso9660, paths, proc

ROOT = paths.repo_root()
GAMES = ROOT / "games"
BASEROM = ROOT / "baserom"
PROGRESS = ROOT / "progress"
GENERATED = "<!-- Generated by tools/openrac.py tables from games/*/game.json; do not edit. -->\n"


# --- Discs ----------------------------------------------------------------------

def checksums(path: Path, full: bool) -> dict:
    """size and sha1, plus crc32, md5 and sha256 when FULL, in one pass over the image (digest's
    helpers read a file once for each)."""
    names = ("sha1", "md5", "sha256") if full else ("sha1",)
    hashes = {n: hashlib.new(n) for n in names}
    crc = 0
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 24), b""):
            for h in hashes.values():
                h.update(block)
            if full:
                crc = zlib.crc32(block, crc)
    out = {"size": path.stat().st_size, **{n: h.hexdigest() for n, h in hashes.items()}}
    if full:
        out["crc32"] = f"{crc:08x}"
    return out


def known_discs() -> dict[str, list[tuple[dict, str, dict]]]:
    """serial -> [(game, version name, version)]: two releases can share a serial (Ratchet &
    Clank's PAL v1.00 and v2.00 both boot SCES_509.16), told apart by their checksums."""
    out: dict[str, list[tuple[dict, str, dict]]] = {}
    for g, name, v in games.versions():
        out.setdefault(v["serial"], []).append((g, name, v))
    return out


def scan(full: bool = False) -> dict[str, Path]:
    """'game/version' -> the image in baserom/ whose checksums match game.json; prints what it finds."""
    known, found = known_discs(), {}
    images = sorted(p for p in BASEROM.glob("*") if p.is_file() and p.suffix.lower() == ".iso")
    if not images:
        print(f"no .iso files in {BASEROM.relative_to(ROOT)}/ (see baserom/README.md)")
    for iso in images:
        serial = iso9660.boot_serial(iso)
        if serial not in known:
            print(f"{iso.name}: {'not a PS2 disc' if serial is None else serial + ', not a disc OpenRAC knows'}")
            continue
        got = checksums(iso, full)
        # A checksum game.json does not record yet (rac5's CRC32 and MD5) is not compared.
        differing = [(game, name, version, [k for k, v in got.items() if k in version["disc"] and version["disc"][k] != v])
                     for game, name, version in known[serial]]
        game, name, version, bad = min(differing, key=lambda d: len(d[3]))
        label = f"{game['title']} ({version['region']}, {serial}"
        label += f", disc v{version['disc']['version']})" if len(known[serial]) > 1 else ")"
        if bad:
            print(f"{iso.name}: {label}, but {', '.join(bad)} differ from games/{game['id']}/game.json")
            continue
        print(f"{iso.name}: {label}, {'all checksums' if full else 'size and SHA-1'} match")
        found[f"{game['id']}/{name}"] = iso
    for serial, releases in known.items():
        for game, name, version in releases:
            if f"{game['id']}/{name}" not in found:
                print(f"missing: {game['title']} ({version['region']}, {serial}) for {games.version_dir(game, name)}")
    return found


# --- Setup ----------------------------------------------------------------------

def place_link(source: Path, dest: Path) -> str:
    """Hard-link SOURCE at DEST (a copy across file systems). Hard links, not symbolic
    ones, so a build container that mounts only part of the tree still sees the file."""
    if dest.exists():
        if dest.stat().st_ino == source.stat().st_ino:
            return "already there"
        return "exists, left alone"
    dest.parent.mkdir(parents=True, exist_ok=True)
    return files.link_or_copy(source, dest)


def place_boot(iso: Path, serial: str, want: dict, dest: Path) -> str:
    if dest.exists():
        return "already there" if digest.sha1(dest) == want["sha1"] else "exists, left alone (other contents)"
    data = iso9660.read(iso, serial)
    if hashlib.sha1(data).hexdigest() != want["sha1"]:
        return "not written: the executable in the image does not match game.json"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_bytes(data)
    return "written"


def place_toolchains(dest: Path) -> str:
    """A relative symbolic link from DEST to the shared toolchains/ directory, which
    the build container sees because it mounts all of OpenRAC."""
    target = Path(os.path.relpath(ROOT / "toolchains", dest.parent))
    if dest.is_symlink() and Path(os.readlink(dest)) == target:
        return "already linked"
    if dest.exists() or dest.is_symlink():
        return "exists, left alone"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.symlink_to(target, target_is_directory=True)
    missing = [] if (ROOT / "toolchains").is_dir() else [" (toolchains/ is empty: see toolchains/README.md)"]
    return f"linked to {target}" + "".join(missing)


def place_symlink(target: Path, dest: Path) -> str:
    """A relative symbolic link from DEST to TARGET, both inside OpenRAC."""
    rel = Path(os.path.relpath(target, dest.parent))
    if dest.is_symlink() and Path(os.readlink(dest)) == rel:
        return "already linked"
    if dest.exists() or dest.is_symlink():
        return "exists, left alone"
    if not target.exists():
        return f"not linked: {target.relative_to(ROOT)} is missing (see toolchains/README.md)"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.symlink_to(rel, target_is_directory=target.is_dir())
    return f"linked to {rel}"


def setup(only: list[str]) -> None:
    found = scan()
    for game, name, version in games.versions():
        key = f"{game['id']}/{name}"
        if only and key not in only:
            continue
        inputs = version.get("inputs", [])
        iso = found.get(key)
        if not inputs:
            print(f"{key}: nothing to place ({version.get('setup', 'no build yet')})")
            continue
        tree = ROOT / games.version_dir(game, name)
        if not (tree / ".git").exists():
            # Placing files in an empty submodule directory would stop git from checking it out.
            print(f"{key}: skipped, {tree.relative_to(ROOT).as_posix()} is not checked out "
                  "(git submodule update --init --depth 1, then python3 tools/sources.py apply)")
            continue
        for item in inputs:
            dest = ROOT / item["path"]
            if item["from"] == "toolchains":
                state = place_toolchains(dest)
            elif item["from"] == "link":
                state = place_symlink(ROOT / item["target"], dest)
            elif iso is None:
                state = "skipped, the disc is missing"
            elif item["from"] == "disc":
                state = place_link(iso, dest)
            else:
                state = place_boot(iso, version["serial"], version["boot"], dest)
            print(f"{key}: {item['path']}: {state}")
        if version.get("setup"):
            print(f"{key}: next, {version['setup']}")


# --- Progress -------------------------------------------------------------------

def fetch_reports() -> None:
    """Copy reports that a sister project publishes outside its tree (progress.fetch)."""
    for game, name, version in games.versions():
        fetch = version.get("progress", {}).get("fetch")
        if not fetch:
            continue
        repo = games.source_checkout(game["id"], name)
        key = f"{game['id']}/{name}"
        try:
            # The fetch shows what git says when it fails; the reads keep it.
            proc.run(["git", "-C", repo, "fetch", "-q", "origin", fetch["branch"]])
            ref = f"origin/{fetch['branch']}"
            data = proc.git(repo, "show", f"{ref}:{fetch['path']}", binary=True)
            commit = proc.git(repo, "log", "-1", "--format=%h %cs", ref).split()
        except (subprocess.CalledProcessError, FileNotFoundError) as e:
            print(f"{key}: could not fetch its report from {repo} ({e})")
            continue
        report = json.loads(data)
        report["openrac_source"] = {"branch": fetch["branch"], "commit": commit[0], "date": commit[1]}
        dest = ROOT / version["progress"]["report"]
        dest.parent.mkdir(parents=True, exist_ok=True)
        dest.write_text(json.dumps(report, indent=1) + "\n", encoding="utf-8")
        print(f"{key}: report from {fetch['branch']} at {commit[0]} ({commit[1]})")


def measure(version: dict, checkout: Path | None = None) -> dict | None:
    """The version's code progress from its own report, in one shape:
    matched/total code bytes, matched/total functions (when counted), fuzzy %, and the date.
    CHECKOUT is the version's sister checkout (games.source_checkout), where the report's date is
    looked up first; without it, OpenRAC's history alone dates the report."""
    progress = version.get("progress")
    if not progress:
        return None
    path = ROOT / progress["report"]
    if not path.exists():
        return {"missing": progress["report"]}
    report = json.loads(path.read_text(encoding="utf-8"))
    if progress["format"] == "objdiff":
        m = report["measures"]
        out = {"matched_code": int(m.get("matched_code", 0)), "total_code": int(m["total_code"]),
               "matched_functions": m.get("matched_functions"), "total_functions": m.get("total_functions"),
               "fuzzy_percent": round(float(m.get("fuzzy_match_percent", 0)), 2)}
        out["date"] = report.get("openrac_source", {}).get("date") or report_date(version, path, checkout)
    else:
        raise SystemExit(f"{progress['report']}: unknown progress format {progress['format']}")
    out["percent"] = round(100.0 * out["matched_code"] / out["total_code"], 2) if out["total_code"] else 0.0
    return out


def report_date(version: dict, path: Path, checkout: Path | None) -> str:
    """When the report last changed: in its sister project's history when CHECKOUT is there and
    the file came from it, else in OpenRAC's."""
    source = version.get("source")
    for repo, rel in ((checkout, None), (ROOT, path)):
        if repo is None or not (repo / ".git").exists():
            continue
        if rel is None:
            game_dir = next((d for d in GAMES.glob("*/*") if d.is_dir() and d in path.parents), None)
            if game_dir is None:
                continue
            rel, rev = path.relative_to(game_dir), source["commit"]
        else:
            rev = "HEAD"
        date = proc.git(repo, "log", "-1", "--format=%cs", rev, "--", rel, check=False)
        if date:
            return date
    return "uncommitted"


def progress(fetch: bool) -> None:
    if fetch:
        fetch_reports()
    rows, summary = [], {}
    for game, name, version in games.versions():
        key = f"{game['id']}/{name}"
        m = measure(version, games.source_checkout(game["id"], name))
        if m is not None:
            # A version with no report yet has no row: the launcher reads each row's progress as
            # figures, and one null made it read none of the file (launcher/core/src/catalog.rs).
            summary[key] = {"title": game["title"], "region": version["region"], "serial": version["serial"],
                            "progress": m, "note": version.get("progress", {}).get("note")}
        rows.append((game, name, version, m))
    PROGRESS.mkdir(exist_ok=True)
    (PROGRESS / "summary.json").write_text(json.dumps(summary, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
    table = render(rows)
    local = table.replace("](games/", "](../games/")   # progress/README.md sits one level down
    (PROGRESS / "README.md").write_text(
        "# Progress\n\n"
        "Generated by `python3 tools/openrac.py progress` from each game's own report; do not\n"
        "edit by hand. Each project measures its own scope (see the notes), so the percentages\n"
        "are comparable within a game, not between games.\n\n" + local + "\n" + notes(rows), encoding="utf-8")
    tables()
    print(table)


def sums(d: dict) -> str:
    """The four checksums' table cells; one a project has not recorded yet is a dash."""
    return " | ".join(f"`{d[k]}`" if d.get(k) else "–" for k in ("crc32", "md5", "sha1", "sha256"))


def size(d: dict) -> str:
    """The size's table cell; a dash when no one has recorded it yet."""
    return f"{d['size']:,}" if d.get("size") else "–"


def disc_table() -> str:
    out = ["| Game | Version | Serial | Size (bytes) | CRC32 | MD5 | SHA-1 | SHA-256 |",
           "|---|---|---|---:|---|---|---|---|"]
    for game, name, v in games.versions():
        d = v["disc"]
        out.append(f"| {game['title']} | {v['region']}, disc v{d['version']} | `{v['serial']}` | {size(d)} | "
                   f"{sums(d)} |")
    return "\n".join(out) + "\n"


def boot_table() -> str:
    out = ["| Game | Version | Boot executable | Size (bytes) | CRC32 | MD5 | SHA-1 | SHA-256 |",
           "|---|---|---|---:|---|---|---|---|"]
    for game, name, v in games.versions():
        b = v["boot"]
        out.append(f"| {game['title']} | {v['region']} | `{b['file']}` | {size(b)} | {sums(b)} |")
    return "\n".join(out) + "\n"


def game_table() -> str:
    out = ["| Game | Version | Directory | Decompiles | Builds on |", "|---|---|---|---|---|"]
    for game, name, v in games.versions():
        where = f"[`{games.version_dir(game, name)}`]({games.version_dir(game, name)})" if v.get("source") else f"[`games/{game['id']}`](games/{game['id']})"
        host = v.get("build", {}).get("host", "–")
        out.append(f"| {game['title']} ({game['year']}) | {v['region']} `{v['serial']}` | {where} | {v['target']} | {host} |")
    return "\n".join(out) + "\n"


def region(version: dict) -> str:
    """A version's region without its gloss: "NTSC-U" for "NTSC-U (North America)"."""
    return version["region"].split(" (")[0]


def decomp_rows(game: dict) -> list[tuple[str, dict, list[str]]]:
    """(folder, source, version names) for each decomp of GAME: its own decomp (every version
    built from it), then each version with a decomp of its own (rac1's NTSC decomp)."""
    rows = []
    if game.get(games.DECOMP):
        shared = [n for n, v in game["versions"].items() if (v.get("source") or {}).get("shared") == games.DECOMP]
        rows.append((games.decomp_dir(game), game[games.DECOMP], shared))
    rows += [(games.version_dir(game, n), v["source"], [n]) for n, v in game["versions"].items()
             if v.get("source") and not v["source"].get("shared")]
    return rows


def source_table() -> str:
    out = ["| Game | Decomp (repository) | Versions it holds | Folder | Pinned at |", "|---|---|---|---|---|"]
    for game in games.load_all():
        for where, s, names in decomp_rows(game):
            held = ", ".join(f"{region(game['versions'][n])} `{game['versions'][n]['serial']}`" for n in names)
            out.append(f"| {game['title']} | [{s['name']}]({s['repo']}) ({s['branch']}) | {held} | "
                       f"[`{where}`]({where}) | `{s['commit'][:12]}` ({s['date']}) |")
    return "\n".join(out) + "\n"


def versions_table(game: dict) -> str:
    """games/<game>/README.md's table: each version, its disc, the decomp it is built from (a folder
    beside the README) and the port's program for it (port/game/<game>-<version>/)."""
    out = ["| Version | Disc | Serial | Decomp | Port |", "|---|---|---|---|---|"]
    for name, v in game["versions"].items():
        source = v.get("source") or {}
        rel = games.decomp_dir(game) if source.get("shared") == games.DECOMP else games.version_dir(game, name)
        named = game[games.DECOMP] if source.get("shared") == games.DECOMP else source
        folder = Path(rel).name
        decomp = f"[{folder}/]({folder}/README.md) ([{named['name']}]({named['repo']}))" if source else "–"
        port = f"{game['id']}-{name}"
        built = (f"[`port/game/{port}/`](../../port/game/{port}/)" if (ROOT / "port/game" / port).is_dir()
                 else "not built yet")
        disc = f"{v['region']}, disc v{v['disc']['version']}" if v.get("disc", {}).get("version") else v["region"]
        out.append(f"| `{game['id']}/{name}` | {disc} | `{v['serial']}` | {decomp} | {built} |")
    return "\n".join(out) + "\n"


# Versions the README's progress leaves out for now: Secret Agent Clank, until bytematch.dev has
# its reports (its badge says "version not found" until then).
PROGRESS_HIDDEN = {"SCUS_976.23"}


def short_title(game: dict, name: str) -> str:
    """A game's name in the README's progress: its title without the series ("Going Commando"),
    and the version ("PAL") when the game has more than one."""
    title = game["title"]
    for series in ("Ratchet & Clank: ", "Ratchet: "):
        title = title.removeprefix(series)
    if len(game["versions"]) == 1:
        return title
    version = game["versions"][name]
    serial = version.get("serial")
    if serial and "disc" in version and sum(v.get("serial") == serial for v in game["versions"].values()) > 1:
        # Two releases of one serial (Going Commando's v1.01 and v2.00): told apart by the disc's version.
        return f"{title} ({version['disc']['video']} v{version['disc']['version']})"
    return f"{title} ({name.upper()})"


def progress_box(versions) -> str:
    """The README's compact progress: a table the page's width, one row per version with a
    ByteMatch project: its name, the decompilation project it comes from, and a live
    bytematch.dev badge of the code it has matched, in the launcher's amber: light enough that
    the badge writes its figure in dark text (it has no option for the text's colour). VERSIONS
    is games.versions()."""
    rows = []
    for game, name, v in versions:
        slug = v.get("bytematch")
        if not slug or v["serial"] in PROGRESS_HIDDEN:
            continue
        title = short_title(game, name)
        source = v.get("source") or {}
        # The NTSC decomp is shown as its project, at the workspace owner's request.
        label = "Lombyte Project" if (game["id"], name) == ("rac1", "ntsc") else source.get("name")
        project = f'<a href="{source["repo"]}">{label}</a>' if source.get("repo") else "–"
        bytematch_version = v.get("bytematch_version", v["serial"])
        query = urlencode({"mode": "shield", "label": "", "measure": "matched_code_percent",
                           "version": bytematch_version, "color": "ffb443", "style": "flat-square"})
        badge = (f'<a href="https://bytematch.dev/{slug}/{bytematch_version}">'
                 f'<img src="https://bytematch.dev/{slug}.svg?{query.replace("&", "&amp;")}" '
                 f'alt="{title}: code decompiled"></a>')
        rows.append(f'  <tr><td>{title.replace("&", "&amp;")}</td><td>{project}</td>'
                    f'<td align="right">{badge}</td></tr>')
    # GitHub sizes a table to its content, whatever its own width says: the columns' widths make
    # it as wide as the README's column.
    return ('<table>\n'
            '  <tr><th align="left" width="260">Game</th><th align="left" width="270">Project</th>'
            '<th align="right" width="190">Code decompiled</th></tr>\n'
            + "\n".join(rows) + "\n</table>\n")


def tables() -> None:
    """Rewrite every <!-- NAME:begin --> ... <!-- NAME:end --> block in README.md and
    baserom/README.md with the table of that name."""
    summary = PROGRESS / "summary.json"
    rows = [(g, n, v, measure(v, games.source_checkout(g["id"], n))) for g, n, v in games.versions()]
    made = {"games": game_table(), "discs": disc_table(), "boot": boot_table(), "sources": source_table(),
            "badges": progress_box(games.versions()),
            "progress": render(rows, dates=False, badges=True) if summary.exists() else None}
    docs = [ROOT / "README.md", BASEROM / "README.md", GAMES / "README.md", ROOT / "docs/SOURCES.md"]
    docs += [GAMES / game["id"] / "README.md" for game in games.load_all()]
    for doc in docs:
        if not doc.exists():
            continue
        text, depth = doc.read_text(encoding="utf-8"), len(doc.relative_to(ROOT).parts) - 1
        own = {"versions": versions_table(games.load(doc.parent.name))} if doc.parent.parent == GAMES else {}
        for name, table in {**made, **own}.items():
            begin, end = f"<!-- {name}:begin -->", f"<!-- {name}:end -->"
            if table is None or begin not in text or end not in text:
                continue
            if depth and name != "versions":
                table = table.replace("](games/", "](" + "../" * depth + "games/")
            head, rest = text.split(begin, 1)
            text = head + begin + "\n" + GENERATED + table + end + rest.split(end, 1)[1]
        doc.write_text(text, encoding="utf-8")


def progress_badge(version: dict, measure: str, label: str) -> str | None:
    """A live bytematch.dev badge for VERSION's project, linked to its page for that version.
    None when the version has no ByteMatch project (the table then keeps its report figures)."""
    slug = version.get("bytematch")
    if not slug:
        return None
    # ByteMatch's id for the version: its serial, unless two releases share one (Going Commando's
    # v2.00 is SCUS_972.68_v2 beside v1.01's SCUS_972.68).
    serial = version.get("bytematch_version", version["serial"])
    query = urlencode({"mode": "shield", "label": label, "measure": measure, "version": serial})
    return f"[![{label}](https://bytematch.dev/{slug}.svg?{query})](https://bytematch.dev/{slug}/{serial})"


def render(rows, dates: bool = True, badges: bool = False) -> str:
    """The progress table. Without DATES it depends only on the committed reports
    and manifests, so CI can check that README.md is current. With BADGES, each
    figure that has a ByteMatch project comes live from bytematch.dev instead."""
    out = ["| Game | Version | Code matched | Functions | Fuzzy |" + (" Report date |" if dates else ""),
           "|---|---|---:|---:|---:|" + ("---|" if dates else "")]
    for game, name, version, m in rows:
        where = f"[`{games.version_dir(game, name)}`]({games.version_dir(game, name)})" if version.get("source") else "not started"
        label = f"{version.get('bytematch_version', version['serial'])} ({where})"
        if m is None:
            code, fns, fuzzy, date = "–", "–", "–", " – " if dates else ""
        elif "missing" in m:
            code, fns, fuzzy, date = f"no report (`{m['missing']}`)", "–", "–", " – " if dates else ""
        else:
            fns = (f"{m['matched_functions']:,} / {m['total_functions']:,}"
                   if m["matched_functions"] is not None else "not counted")
            fuzzy = f"{m['fuzzy_percent']:.2f}%" if m["fuzzy_percent"] is not None else "–"
            code = f"{m['percent']:.2f}% ({m['matched_code']:,} / {m['total_code']:,} bytes)"
            date = f" {m['date']} " if dates else ""
        if badges:
            code = progress_badge(version, "matched_code_percent", "Code") or code
            if m is not None and "missing" not in m:
                fns = progress_badge(version, "matched_functions", "Functions") or fns
                fuzzy = progress_badge(version, "fuzzy_match_percent", "Fuzzy") or fuzzy
        tail = f"|{date}|" if dates else "|"
        out.append(f"| {game['title']} | {label} | {code} | {fns} | {fuzzy} {tail}")
    return "\n".join(out) + "\n"


def notes(rows) -> str:
    lines = [f"- **{game['id']}/{name}**: {version['progress']['note']}"
             for game, name, version, _ in rows if version.get("progress", {}).get("note")]
    return ("## Notes\n\n" + "\n".join(lines) + "\n") if lines else ""


def main() -> None:
    args = sys.argv[1:]
    if args[:1] == ["discs"]:
        scan(full="--full" in args)
