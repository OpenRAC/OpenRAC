"""Tests for tools/dup_check.py: what counts as a copy and what does not."""
import sys
import unittest
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import dup_check  # noqa: E402

FIELDS = ["speed", "angle", "height", "width", "depth", "radius", "mass", "drag", "spin", "glow", "fade", "tint"]
BODY = "\n".join(f"total += table.{f} * scale; count = count + step;" for f in FIELDS)


def function(name: str, body: str = BODY) -> str:
    return f"int {name}(int scale, int step) {{\n int total = 0; int count = 0;\n{body}\n return total; }}\n"


class Copies(unittest.TestCase):
    def find(self, files):
        return dup_check.find_copies({k: dup_check.tokens_of(v) for k, v in files.items()}, 40)

    def test_the_same_function_in_two_files_is_one_copy(self):
        copies = self.find({"a.c": function("f"), "b.c": function("f")})
        self.assertEqual(len(copies), 1)
        self.assertEqual(copies[0].files, ("a.c", "b.c"))

    def test_numbers_strings_and_comments_do_not_hide_a_copy(self):
        other = function("f", BODY.replace("scale;", "scale + 99;", 1)).replace("return total;", "/* x */ return total;")
        self.assertEqual(len(self.find({"a.c": function("f"), "b.c": other})), 1)

    def test_different_names_are_not_a_copy(self):
        other = function("f", BODY.replace("table", "other").replace("count", "n").replace("total", "sum"))
        self.assertEqual(self.find({"a.c": function("f"), "b.c": other}), [])

    def test_a_short_run_is_not_a_copy(self):
        short = "int f(int a) { return a + 1; }\n"
        self.assertEqual(self.find({"a.c": short, "b.c": short}), [])

    def test_the_baseline_line_ignores_where_the_copy_sits(self):
        moved = "\n\n\n// header\n" + function("f")
        first = self.find({"a.c": function("f"), "b.c": function("f")})[0]
        second = self.find({"a.c": moved, "b.c": function("f")})[0]
        self.assertEqual(first.baseline_line(), second.baseline_line())

    def test_tests_and_generated_files_are_out_of_scope(self):
        self.assertTrue(dup_check.is_test("port/tests/check_test.cpp"))
        self.assertTrue(dup_check.is_test("port/audio/mixer_test.cpp"))
        self.assertFalse(dup_check.is_test("port/audio/mixer.cpp"))
        self.assertTrue(dup_check.is_generated("// Generated by x.py. Do not edit.\nint a;"))


if __name__ == "__main__":
    unittest.main()
