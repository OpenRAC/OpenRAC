#!/usr/bin/env python3
"""
Use moby class names instead of numbers.

  python3 tools/tidy/moby_classes.py header           # write include/enums/moby_class.h
  python3 tools/tidy/moby_classes.py apply            # dry run: show counts
  python3 tools/tidy/moby_classes.py apply --write
  python3 tools/tidy/moby_classes.py apply --list     # show the comment changes

Names come from tools/extract/moby_classes.tsv. In code, `oclass == 0x3EF` and the cases of `switch (m->oclass)` become
enum names: an enum value is the same number, so the bytes do not change. In comments, `class 0x3EF` becomes the
class's name. A number with no name stays as it is. The provenance part of a comment is never changed.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import prune_externs as pe  # noqa: E402

ROOT = pe.ROOT
TABLE = ROOT / "tools/extract/moby_classes.tsv"
HEADER = ROOT / "include/enums/moby_class.h"
INCLUDE = '#include "enums/moby_class.h"'
NUMBER = r"(0[xX][0-9A-Fa-f]+|[0-9]+)"
COMPARE = re.compile(r"(\boclass\s*[!=]=\s*)" + NUMBER + r"\b")
SWITCH = re.compile(r"\bswitch\s*\(([^()]|\([^()]*\))*\boclass\b([^()]|\([^()]*\))*\)\s*\{")
CASE = re.compile(r"\bcase\s+" + NUMBER + r"\s*:")
COMMENT = re.compile(r"/\*.*?\*/|//[^\n]*", re.S)
# Comment forms, longest first: each gives the words that replace it.
OF_CLASS = re.compile(r"\b(\w+) of class " + NUMBER + r"\b")
CLASS_MOBY = re.compile(r"\bclass " + NUMBER + r" (mobys?)\b")
IN_PARENS = re.compile(r"\(class " + NUMBER + r"\)")
BARE = re.compile(r"\bclass " + NUMBER + r"\b")
PROVENANCE_START = re.compile(r"Adapted from|Lombyte|GPL|\(c\)", re.I)

# Names the enum had before the table was used. They stay, so no code has to change for them.
KEPT_NAMES = {
    0xD: "BOLT_CLASS_ONE", 0xE: "BOLT_CLASS_FIVE", 0xF: "BOLT_CLASS_TWENTY", 0x10: "BOLT_CLASS_FIFTY",
}


def read_table(path=TABLE):
    """{class number: name} from the table."""
    table = {}
    for line in path.read_text().splitlines():
        if line and not line.startswith("#"):
            number, name = line.split("\t")[:2]
            table[int(number)] = name
    return table


def existing_enum(path=HEADER):
    """{class number: enum name} for what the header holds now."""
    if not path.exists():
        return {}
    return {int(value, 16): name for name, value in re.findall(r"^\s*(\w+) = (0x[0-9A-Fa-f]+),?", path.read_text(), re.M)}


def enum_names(table, kept):
    """{class number: enum name}. A name used by two classes gets its number added, so both stay clear."""
    counts = {}
    for name in table.values():
        counts[name] = counts.get(name, 0) + 1
    names = dict(kept)
    for number, name in table.items():
        if number in names:
            continue
        cleaned = re.sub(r"\W", "_", name).upper()
        names[number] = f"MOBY_CLASS_{cleaned}" + (f"_{number}" if counts[name] > 1 else "")
    return names


def display_name(name):
    """white_flower -> White Flower"""
    return " ".join(word.capitalize() for word in re.split(r"[\W_]+", name) if word)


def header_text(names):
    lines = ["#ifndef MOBY_CLASS_ID_H", "#define MOBY_CLASS_ID_H", "", "/*",
             " * Moby class IDs (Moby.oclass). Generated by tools/tidy/moby_classes.py header; do not edit.",
             " *", " * Most names are from tools/extract/moby_classes.tsv: Lombyte's project (MIT) and Wrench's moby",
             " * class list. Some are from the NTSC decomp (Lombyte's project, GPL-3.0). Enumerations only: no layout,",
             " * no code. See THIRD_PARTY_NOTICES.md.", " *",
             " * A name that two classes share has its class number added.", " */", "", "enum MobyClassId {"]
    lines += [f"    {names[number]} = 0x{number:X}," for number in sorted(names)]
    lines += ["};", "", "#endif /* MOBY_CLASS_ID_H */", ""]
    return "\n".join(lines)


def rewrite_comment(comment, table):
    """Names for class numbers in a comment, before any provenance part."""
    start = PROVENANCE_START.search(comment)
    head, tail = (comment[:start.start()], comment[start.start():]) if start else (comment, "")

    def name_of(number):
        return table.get(int(number, 0))

    def of_class(m):
        name = name_of(m.group(2))
        if not name:
            return m.group(0)
        return f"{display_name(name)}" if m.group(1).lower() in ("a", "an", "any", "the") else (
            f"{m.group(1)} of {display_name(name)}" if m.group(1).lower() in ("one", "each", "every", "all", "list")
            else f"{display_name(name)} {m.group(1)}")

    def class_moby(m):
        name = name_of(m.group(1))
        return f"{display_name(name)} {m.group(2)}" if name else m.group(0)

    def in_parens(m):
        name = name_of(m.group(1))
        if not name:
            return m.group(0)
        # "Bomber tank (class 0x12)": the comment already has the name.
        words = re.sub(r"[\W_]+", " ", m.string[:m.start()]).strip().lower()
        spaced = display_name(name).lower()
        return "\0" if words.endswith(spaced) else f"({display_name(name)})"

    def bare(m):
        name = name_of(m.group(1))
        return display_name(name) if name else m.group(0)

    for pattern, function in ((OF_CLASS, of_class), (CLASS_MOBY, class_moby), (IN_PARENS, in_parens), (BARE, bare)):
        head = pattern.sub(function, head)
    return re.sub(r" ?\0", "", head) + tail


def outside_comments_and_strings(text, function):
    """Apply a function to the code only."""
    out, last = [], 0
    for m in pe.COMMENT_OR_STRING.finditer(text):
        out.append(function(text[last:m.start()]))
        out.append(m.group(0))
        last = m.end()
    out.append(function(text[last:]))
    return "".join(out)


def rewrite_switches(text, names, switch=SWITCH):
    """Case labels of a matching switch, at the switch's own level only."""
    masked = pe.COMMENT_OR_STRING.sub(pe.blank, text)
    edits = []
    for m in switch.finditer(masked):
        depth, i = 1, m.end()
        while i < len(masked) and depth:
            if masked[i] == "{":
                depth += 1
            elif masked[i] == "}":
                depth -= 1
            elif depth == 1 and masked[i:i + 4] == "case":
                case = CASE.match(masked, i)
                if case and int(case.group(1), 0) in names:
                    edits.append((case.start(1), case.end(1), names[int(case.group(1), 0)]))
            i += 1
    for start, end, name in sorted(edits, reverse=True):
        text = text[:start] + name + text[end:]
    return text, len(edits)


def rewrite_code(text, names):
    """(new text, number of literals replaced)."""
    count = [0]

    def compare(m):
        number = int(m.group(2), 0)
        if number not in names:
            return m.group(0)
        count[0] += 1
        return m.group(1) + names[number]

    text = outside_comments_and_strings(text, lambda code: COMPARE.sub(compare, code))
    text, cases = rewrite_switches(text, names)
    return text, count[0] + cases


def rewrite_comments(text, table):
    """(new text, comments changed, [(old, new)])."""
    changes = []

    def one(m):
        new = rewrite_comment(m.group(0), table)
        if new != m.group(0):
            changes.append((m.group(0), new))
        return new

    # Only real comments: a comment marker inside a string stays.
    out, last = [], 0
    for m in pe.COMMENT_OR_STRING.finditer(text):
        out.append(text[last:m.start()])
        out.append(one(m) if m.group(0)[0] == "/" else m.group(0))
        last = m.end()
    out.append(text[last:])
    return "".join(out), changes


def add_include(text):
    if INCLUDE in text:
        return text
    first = re.search(r"^#include [^\n]*\n(?:#include [^\n]*\n)*", text, re.M)
    at = first.end() if first else 0
    return text[:at] + INCLUDE + "\n" + text[at:]


def main():
    args = sys.argv[1:]
    table = read_table()
    if args[:1] == ["header"]:
        kept = dict(KEPT_NAMES)
        kept.update(existing_enum())
        names = enum_names(table, kept)
        HEADER.write_text(header_text(names))
        print(f"wrote {len(names)} names to {HEADER.relative_to(ROOT)}")
        return
    if args[:1] != ["apply"]:
        sys.exit(__doc__)
    write, listing = "--write" in args, "--list" in args
    names = existing_enum()
    literals = comments = 0
    for rel in pe.sources(["src"]):
        path = ROOT / rel
        text = path.read_text(errors="surrogateescape")
        new, count = rewrite_code(text, names)
        fragments = sorted((ROOT / "src/versions").glob(f"*/{rel[len('src/'):-len('.c')]}/*.c"))
        changed_fragments = {}
        for fragment in fragments:
            old = fragment.read_text(errors="surrogateescape")
            after, fragment_count = rewrite_code(old, names)
            after, fragment_changes = rewrite_comments(after, table)
            count += fragment_count
            comments += len(fragment_changes)
            if after != old:
                changed_fragments[fragment] = (after, fragment_count)
        used = count > 0
        new, changes = rewrite_comments(new, table)
        comments += len(changes)
        literals += count
        if listing:
            for old, after in changes:
                print(f"{rel}: {' '.join(after.split())[:110]}")
        if used:
            new = add_include(new)
        if write:
            if new != text:
                path.write_text(new, errors="surrogateescape")
            for fragment, (after, _) in changed_fragments.items():
                fragment.write_text(after, errors="surrogateescape")
    print(f"{'replaced' if write else 'would replace'} {literals} literals and {comments} comments")


if __name__ == "__main__":
    main()
