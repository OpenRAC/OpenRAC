#!/usr/bin/env python3
"""
Find code that matches retail but is probably not what the authors wrote.

  python3 tools/fakematch_scan.py --tag     # add FAKEMATCH comments, and write config/fakematch.tsv
  python3 tools/fakematch_scan.py --check   # fail if the tags and config/fakematch.tsv disagree

Kinds it tags:
  marked       a comment already said Fakematch
  volatile     volatile on an ordinary variable: it only forces a load or store order
  register     the register keyword: it steers this compiler's register allocation
  if_zero      a dead `if (0)` block
  redeclared   a global declared again inside a function with another type: it can steer addressing

Kinds it lists but does not tag:
  padding      a top-level nop block: retail's own padding between functions
  kept         a KEPT comment: someone read this site and gave a reason it stays

It leaves out, on purpose:
  - src/core and src/libgcc: Sony's and newlib's code. Volatile there polls semaphores and hardware.
  - src/game/movie.
  - volatile on a hardware register address.
  - goto: newlib and other original code really use it, so a goto proves nothing.

A tag means "look at this", not "this is wrong": some hits may turn out to be what the authors wrote.
"""
import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent / "tidy"))
import prune_externs as pe  # noqa: E402

ROOT = pe.ROOT
TABLE = ROOT / "config/fakematch.tsv"
TAG = "FAKEMATCH:"
KEPT = "KEPT:"
HEADER = ("# Code that matches retail but is probably not what the authors wrote. Generated by tools/fakematch_scan.py.\n"
          "# file\tfunction\tkind\treason\n")
REASONS = {
    "volatile": "volatile on an ordinary variable forces a load or store order",
    "register": "the register keyword steers register allocation",
    "if_zero": "a dead if (0) block changes the code around it",
    "redeclared": "a redeclaration with another type can steer how the global is addressed",
    "padding": "retail's padding between functions",
}
LEFT_OUT = ("src/core/", "src/libgcc/", "src/game/movie/")
HARDWARE = re.compile(r"\b0x1[0-9A-Fa-f]{7}\b")
VOLATILE = re.compile(r"\bvolatile\b")
REGISTER = re.compile(r"\bregister\b")
# Inline asm is left alone (docs/STYLE.md): `__asm__ volatile` and a register pinned for it are not hacks to remove.
ASM_STATEMENT = re.compile(r"\b__asm__\b|\basm\b")
IF_ZERO = re.compile(r"\bif\s*\(\s*0\s*\)")
MARKED = re.compile(r"/\*\s*Fakematch:", re.I)
DEFINITION = re.compile(r"^[A-Za-z_][^;{}=\n]*?\b(\w+)\s*\([^;{}]*\)\s*\{", re.M)
PADDING = re.compile(r'^__asm__\(\s*"\.section \.text[^;]*?nop\b', re.M)


def sources():
    out = subprocess.run(["git", "ls-files", "src/*.c"], cwd=ROOT, capture_output=True, text=True, check=True).stdout
    return [f for f in out.split() if not f.startswith(LEFT_OUT) and not re.match(r"src/versions/[^/]+/game/movie/", f)]


def function_lines(masked):
    """[(first line, last line, name)] of each function, 1-based."""
    found = []
    for m in DEFINITION.finditer(masked):
        depth, i = 1, m.end()
        while i < len(masked) and depth:
            depth += (masked[i] == "{") - (masked[i] == "}")
            i += 1
        found.append((masked.count("\n", 0, m.start()) + 1, masked.count("\n", 0, i) + 1, m.group(1)))
    return found


def function_at(functions, line):
    for first, last, name in functions:
        if first <= line <= last:
            return name
    return "-"


def line_hits(text):
    """[(line number, kind)] of hits found by reading this file's code. A KEPT comment above a line settles it."""
    masked = pe.COMMENT_OR_STRING.sub(pe.blank, text)
    lines = masked.split("\n")
    source = text.split("\n")
    kept = {n for n in range(2, len(source) + 1) if KEPT in source[n - 2]}
    hits = []
    functions = function_lines(masked)
    for number, line in enumerate(lines, 1):
        if number in kept:
            continue
        inside = function_at(functions, number) != "-"
        if VOLATILE.search(line) and not HARDWARE.search(text.split("\n")[number - 1]) and inside:
            if not ASM_STATEMENT.search(line):
                hits.append((number, "volatile"))
        if REGISTER.search(line) and inside and not ASM_STATEMENT.search(line):
            hits.append((number, "register"))
        if IF_ZERO.search(line):
            hits.append((number, "if_zero"))
    return hits


def padding_count(text):
    return len(PADDING.findall(pe.COMMENT_OR_STRING.sub(lambda m: m.group(0) if m.group(0)[0] == '"' else pe.blank(m), text)))


def redeclared_lines():
    """{file: [line]} for block-scope redeclarations, from clang. Only the shared files can be parsed."""
    sys.path.insert(0, str(ROOT / "tools"))
    import check_syntax as cs
    cs.clast.prep_includes()
    found = {}
    for rel in cs.sources():
        if rel.startswith(LEFT_OUT):
            continue
        _, errors = cs.errors_in(rel)
        for line in errors:
            m = re.search(r":(\d+):\d+: error: (redeclaration of|conflicting types for|cannot apply asm label)", line)
            if m:
                found.setdefault(rel, set()).add(int(m.group(1)))
    return {rel: sorted(lines) for rel, lines in found.items()}


def add_tags(text, hits):
    """(new text, tags added): a comment above each hit, once per line and kind."""
    lines = text.split("\n")
    added = 0
    for number, kind in sorted(set(hits), reverse=True):
        indent = re.match(r"\s*", lines[number - 1]).group(0)
        above = lines[number - 2] if number >= 2 else ""
        if TAG in above or TAG in lines[number - 1] or KEPT in above:
            continue
        lines.insert(number - 1, f"{indent}/* {TAG} {REASONS[kind]}. */")
        added += 1
    return "\n".join(lines), added


def mark_existing(text):
    """Comments that already say Fakematch get the one spelling."""
    return MARKED.sub(f"/* {TAG}", text)


def table_rows(rel, text):
    """[(file, function, kind, reason)] for every tag in this file, plus its padding."""
    masked = pe.COMMENT_OR_STRING.sub(pe.blank, text)
    functions = function_lines(masked)
    rows = []
    for number, line in enumerate(text.split("\n"), 1):
        at = line.find(TAG)
        if at < 0:
            continue
        reason = line[at + len(TAG):].split("*/")[0].strip().rstrip(".")
        kind = next((k for k, r in REASONS.items() if reason == r), "marked")
        # A tag above a function's first line belongs to the code below it.
        rows.append((rel, function_at(functions, number + 1), kind, " ".join(reason.split())[:110]))
    for number, line in enumerate(text.split("\n"), 1):
        at = line.find(KEPT)
        if at >= 0:
            reason = " ".join(line[at + len(KEPT):].split("*/")[0].split()).rstrip(".")
            rows.append((rel, function_at(functions, number + 1), "kept", reason[:110]))
    rows += [(rel, "-", "padding", REASONS["padding"])] * padding_count(text)
    return rows


def render(rows):
    return HEADER + "".join("\t".join(row) + "\n" for row in sorted(rows))


def main():
    mode = (sys.argv[1:] or ["--check"])[0]
    files = sources()
    if mode == "--tag":
        redeclared = redeclared_lines()
        total = 0
        for rel in files:
            path = ROOT / rel
            text = path.read_text(errors="surrogateescape")
            new = mark_existing(text)
            hits = line_hits(new) + [(n, "redeclared") for n in redeclared.get(rel, [])]
            new, added = add_tags(new, hits)
            total += added
            if new != text:
                path.write_text(new, errors="surrogateescape")
        print(f"{total} tags added")
    elif mode != "--check":
        sys.exit(__doc__)
    rows = [row for rel in files for row in table_rows(rel, (ROOT / rel).read_text(errors="surrogateescape"))]
    if mode == "--tag":
        TABLE.write_text(render(rows))
    elif not TABLE.exists() or TABLE.read_text() != render(rows):
        sys.exit("*** config/fakematch.tsv disagrees with the FAKEMATCH tags: run tools/fakematch_scan.py --tag")
    kinds = {}
    for row in rows:
        kinds[row[2]] = kinds.get(row[2], 0) + 1
    print(f"{len(rows)} rows: " + ", ".join(f"{n} {kind}" for kind, n in sorted(kinds.items())))


if __name__ == "__main__":
    main()
